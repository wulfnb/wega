//! Supported property names (for `@supports`).

pub fn supported_property(property: &str) -> bool {
    matches!(
        property,
        "visibility" | "pointer-events" | "vertical-align" | "cursor"
    ) || property.starts_with("--")
        || matches!(
            property,
            "align-items"
                | "background"
                | "background-color"
                | "background-image"
                | "background-position"
                | "background-size"
                | "background-repeat"
                | "clip-path"
                | "bold"
                | "border"
                | "border-bottom"
                | "border-color"
                | "border-left"
                | "border-radius"
                | "border-right"
                | "border-spacing"
                | "border-top"
                | "border-width"
                | "bottom"
                | "box-shadow"
                | "box-sizing"
                | "center"
                | "color"
                | "column-gap"
                | "display"
                | "flex-basis"
                | "flex-direction"
                | "flex-grow"
                | "flex-shrink"
                | "flex-wrap"
                | "font-family"
                | "font-size"
                | "font-style"
                | "font-weight"
                | "gap"
                | "grid-column"
                | "grid-column-start"
                | "grid-row"
                | "grid-row-start"
                | "grid-template-columns"
                | "grid-template-rows"
                | "grid-template-areas"
                | "grid-template"
                | "grid-area"
                | "grid-column-end"
                | "grid-row-end"
                | "float"
                | "clear"
                | "height"
                | "justify-content"
                | "left"
                | "line-height"
                | "margin"
                | "margin-bottom"
                | "margin-left"
                | "margin-right"
                | "margin-top"
                | "max-height"
                | "max-width"
                | "min-height"
                | "min-width"
                | "normal"
                | "object-fit"
                | "object-position"
                | "opacity"
                | "overflow"
                | "overflow-x"
                | "overflow-y"
                | "padding"
                | "padding-bottom"
                | "padding-left"
                | "padding-right"
                | "padding-top"
                | "position"
                | "right"
                | "row-gap"
                | "text-align"
                | "top"
                | "transform"
                | "transform-origin"
                | "white-space"
                | "width"
                | "z-index"
        )
}
